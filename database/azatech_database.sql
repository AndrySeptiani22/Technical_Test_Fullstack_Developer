CREATE OR REPLACE FUNCTION audit_row_change() RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_before  jsonb;
    v_after   jsonb;
    v_user    uuid;
    v_request text;
    v_changed jsonb := '[]'::jsonb;
BEGIN
    v_user    := NULLIF(current_setting('app.user_id', true), '')::uuid;
    v_request := NULLIF(current_setting('app.request_id', true), '');

    IF TG_OP = 'UPDATE' THEN
        IF (v_before - 'UPDATED_AT') = (v_after - 'UPDATED_AT') THEN
            RETURN NULL;
        END IF;

        SELECT COALESCE(jsonb_agg(a.key ORDER BY a.key), '[]'::jsonb)
          INTO v_changed
          FROM jsonb_each(v_after) a
         WHERE a.key <> 'UPDATED_AT'
           AND v_before -> a.key IS DISTINCT FROM a.value;
    END IF;

    INSERT INTO "AUDIT_LOGS"
        ("REQUEST_ID", "USER_ID", "ACTION", "ENTITY_TYPE", "ENTITY_ID",
         "BEFORE_DATA", "AFTER_DATA", "METADATA")
    VALUES (
        v_request,
        v_user,
        TG_OP,  
        TG_TABLE_NAME,
        COALESCE(v_after, v_before) ->> TG_ARGV[0],
        v_before,
        v_after,
        jsonb_build_object('changed_fields', v_changed, 'source', 'trigger')
    );

    RETURN NULL;  
END;
$$;

