CREATE OR REPLACE FUNCTION set_order_number() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    n bigint;
BEGIN
    IF NEW."ORDER_NUMBER" IS NULL THEN
        n := nextval('order_number_seq');
        NEW."ORDER_NUMBER" := 'INV-'
            || to_char(NEW."ORDER_DATE" AT TIME ZONE 'Asia/Jakarta', 'YYYYMMDD')
            || '-'
            || CASE WHEN n < 10000 THEN lpad(n::text, 4, '0') ELSE n::text END;
    END IF;
    RETURN NEW;
END;
$$;

